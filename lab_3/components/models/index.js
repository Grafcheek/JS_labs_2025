(function validateData() {
    const requiredProductFields = ['id', 'title', 'type', 'elements'];
    const requiredElementFields = ['title', 'description', 'src', 'details'];
    
    productsData.forEach(product => {
      requiredProductFields.forEach(field => {
        if (!(field in product)) {
          console.error(`Missing product field: ${field} in`, product);
        }
      });
      
      product.elements.forEach(element => {
        requiredElementFields.forEach(field => {
          if (!(field in element)) {
            console.error(`Missing element field: ${field} in`, element);
          }
        });
        
        if (!Array.isArray(element.details)) {
          console.error(`Details should be array in`, element);
        }
      });
    });
})(); 